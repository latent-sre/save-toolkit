def parse_frontmatter(path: Path) -> tuple[dict[str, object], str, list[str]]:
    """Compatibility wrapper over the one shared strict parser."""
    parsed = fleet_frontmatter.parse_file(path, mode="strict")
    return parsed.fields, parsed.body, list(parsed.raw_lines)


def _tool_base(spec: str) -> str:
    return spec.split("(", 1)[0].strip()


def _delegation_targets(specs: list[str], source: Path) -> list[str] | None:
    """Translate exact plugin-qualified ``Agent(plugin:target, ...)`` grants to bare Copilot names.

    Omitting Copilot's ``agents:`` field allows every eligible subagent, so a canonical Agent
    grant must never degrade to an unscoped ``agent`` tool. Canonical validation independently
    checks the fleet graph; this parser keeps the generated metadata scoped when invoked on an
    individual source or fixture. Host runtime enforcement remains version-specific and must be
    verified separately.
    """

    targets: list[str] = []
    for spec in specs:
        if _tool_base(spec) != "Agent":
            continue
        match = re.fullmatch(r"Agent\(([^()]*)\)", spec)
        if match is None:
            raise ValueError(f"{source}: Agent tool must declare an explicit target allowlist")
        for target in (item.strip() for item in match.group(1).split(",")):
            if not re.fullmatch(rf"{re.escape(PLUGIN_NAME)}:[a-z0-9]+(?:-[a-z0-9]+)*", target):
                raise ValueError(f"{source}: invalid Agent target {target!r}")
            target = target.removeprefix(f"{PLUGIN_NAME}:")
            if target in targets:
                raise ValueError(f"{source}: duplicate Agent target {target!r}")
            targets.append(target)
    return targets or None


def _copilot_handoffs(source_agent: str) -> list[dict[str, object]] | None:
    """Offer human-selected transitions across the explicit local ownership graph.

    VS Code handoffs retain conversation context. The external-only ``researcher`` therefore stays
    a sanitized subagent call and never becomes a handoff target. Handoffs are independent of the
    model-call ``agents:`` allowlist: a terminal source may offer a user-controlled transition to a
    new owner without receiving delegation authority itself. No handoff manufactures approval for
    the receiving lane.
    """

    handoffs = COPILOT_HANDOFFS_BY_SOURCE.get(source_agent)
    return [dict(handoff) for handoff in handoffs] if handoffs else None


def _installed_resource(match: re.Match[str]) -> str:
    kind, name, tail = match.group("kind"), match.group("name"), match.group("tail")
    if kind == "agents":
        return f"the installed `{name}` agent definition"
    if not tail or tail == "/SKILL.md":
        return f"the installed `{name}` skill"
    if tail.startswith("/scripts/"):
        raise ValueError(
            f"{name}{tail}: use a relative Markdown link to the bundled script and resolve its "
            "installed absolute path before execution; a workspace-relative path is not portable"
        )
    return f"the installed `{name}` skill's `{tail.lstrip('/')}` resource"


def adapt_text(text: str, host: str) -> str:
    """Remove Claude-only runtime addressing while preserving the authored method."""

    if host != "copilot":
        raise ValueError(f"unknown host {host!r}")
    # Strip the Claude-only addressing banner by shape, not by exact bytes: a two-line wrapped
    # variant once slipped past an exact-string match and shipped into both host projections.
    text = PLUGIN_BANNER_RE.sub("", text, count=1)
    text = PLUGIN_TOKEN_RE.sub("", text)
    text = PLUGIN_PATH_RE.sub(_installed_resource, text)
    text = text.replace("`.claude/agents/", "`agents/")
    text = text.replace("`.claude/skills/", "`skills/")
    text = text.replace("`.claude/commands/", "`commands/")
    return text


def _description(fields: dict[str, object], source: Path) -> str:
    description = fields.get("description")
    if not isinstance(description, str) or not description.strip():
        raise ValueError(f"{source}: missing description")
    return description.strip()


def render_copilot_agent(source: Path, *, command_preview: bool = False) -> str:
    fields, body, _ = parse_frontmatter(source)
    name = str(fields.get("name") or "")
    tool_specs = _split_tool_specs(fields.get("tools"))
    tools = {_tool_base(item) for item in tool_specs}
    delegation_targets = _delegation_targets(tool_specs, source)
    handoffs = _copilot_handoffs(name)
    mapped = {
        COPILOT_TOOL_MAP[item] for item in tools if item in COPILOT_TOOL_MAP
    } | {
        COPILOT_MCP_TOOL_MAP[item] for item in tools if item in COPILOT_MCP_TOOL_MAP
    }
    if name == "sre-assistant":
        mapped.update(native for item in tools for native in COPILOT_NATIVE_BROWSER_MAP.get(item, ()))
    if name in GUARDED_AGENTS:
        mapped.discard("execute")
    ordered = [tool for tool in COPILOT_TOOL_ORDER if tool in mapped]
    ordered.extend(sorted(tool for tool in mapped if tool not in COPILOT_TOOL_ORDER))
    if name in GUARDED_AGENTS and command_preview:
        ordered.extend(["execute/runInTerminal", "execute/getTerminalOutput"])
    # No generated preface: the projection is the canonical body with Claude-only addressing
    # removed. A host limitation that changes what a lane may do is stated in that lane's own
    # body (`sre-assistant` says it has no shell on Copilot), so it travels with the rule it
    # qualifies instead of in a header every agent repeats.
    prompt_body = adapt_text(body, "copilot")
    prompt_limit = SRE_AGENT_PROMPT_MAX_CHARS if name == "sre-assistant" else COPILOT_AGENT_PROMPT_MAX_CHARS
    if len(prompt_body) > prompt_limit:
        raise ValueError(
            f"{source}: generated Copilot agent prompt body is {len(prompt_body):,} characters; "
            f"it exceeds the {prompt_limit:,}-character maximum"
        )
    frontmatter = (
        "---\n"
        f"name: {json.dumps(name, ensure_ascii=False)}\n"
        f"description: {json.dumps(adapt_text(_description(fields, source), 'copilot'), ensure_ascii=False)}\n"
        f"tools: {json.dumps(ordered)}\n"
    )
    if delegation_targets is not None:
        frontmatter += f"agents: {json.dumps(delegation_targets)}\n"
    if handoffs is not None:
        frontmatter += f"handoffs: {json.dumps(handoffs, ensure_ascii=False)}\n"
    if name in GUARDED_AGENTS and command_preview:
        # Agent frontmatter hooks do not get plugin-hook root substitution in VS Code 1.138.
        # This locally exported profile is bound to this checkout/install on the execution host.
        guard_dir = (source.resolve().parents[1] / "scripts").as_posix()
        scoped_hooks = {"PreToolUse": [{
            "type": "command",
            "command": 'sh "$SAVE_TOOLKIT_GUARD_DIR/readonly-guard-copilot-hook.sh"',
            "windows": '& "$env:SAVE_TOOLKIT_GUARD_DIR/readonly-guard-hook.ps1" -Copilot',
            "env": {"SAVE_TOOLKIT_GUARD_DIR": guard_dir},
            "timeout": 15,
        }]}
        frontmatter += f"target: vscode\nhooks: {json.dumps(scoped_hooks)}\n"
    return (
        frontmatter
        + "---\n\n"
        + prompt_body
    )


def _portable_skill(
    source: Path, host: str
) -> tuple[bytes, bool]:
    fields, body, raw_lines = parse_frontmatter(source)
    explicit = str(fields.get("name")) in MANUAL_ONLY or fields.get("disable-model-invocation") == "true"
    portable_frontmatter = adapt_text("\n".join(raw_lines), host)
    note = ""
    if explicit:
        note = "> This skill is explicit-only through Copilot's frontmatter switch.\n\n"
    rendered = (
        "---\n"
        + portable_frontmatter
        + "\n---\n\n"
        + note
        + adapt_text(body, host)
    )
    return rendered.encode("utf-8"), explicit


def _is_runtime_byproduct(path: Path) -> bool:
    return "__pycache__" in path.parts or path.suffix.lower() in RUNTIME_SUFFIXES


def _is_link_or_reparse(path: Path) -> bool:
    if path.is_symlink():
        return True
    try:
        attrs = getattr(path.lstat(), "st_file_attributes", 0)
    except OSError:
        return False
    return bool(attrs & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0))


def _assert_no_indirection_below(root: Path, path: Path, label: str) -> None:
    """Reject links/reparse points in every existing component below ``root``.

    Checking only the leaf is insufficient: a normal-looking ``.github/agents`` directory can
    still escape the repository when ``.github`` itself is a junction or symlink.
    """

    root = root.resolve()
    try:
        relative = path.relative_to(root)
    except ValueError as exc:
        raise ValueError(f"{path}: {label} must remain below {root}") from exc
    current = root
    for component in relative.parts:
        current /= component
        if (current.exists() or current.is_symlink()) and _is_link_or_reparse(current):
            raise ValueError(f"{current}: {label} must not traverse a link/reparse point")


def _canonical_skill_files(root: Path) -> list[Path]:
    result: list[Path] = []
    skill_root = root / "skills"
    _assert_no_indirection_below(root, skill_root, "canonical source")
    for current, directories, files in os.walk(skill_root, followlinks=False):
        current_path = Path(current)
        if _is_link_or_reparse(current_path):
            raise ValueError(f"{current_path}: canonical source must not be a link/reparse point")
        for directory in list(directories):
            child = current_path / directory
            if _is_link_or_reparse(child):
                raise ValueError(f"{child}: canonical source must not be a link/reparse point")
        for filename in files:
            path = current_path / filename
            if _is_runtime_byproduct(path):
                continue
            if _is_link_or_reparse(path):
                raise ValueError(f"{path}: canonical source must not be a link/reparse point")
            result.append(path)
    return sorted(result)


def expected_outputs(root: Path) -> dict[Path, bytes]:
    root = root.resolve()
    outputs: dict[Path, bytes] = {}
    _assert_no_indirection_below(root, root / "agents", "canonical source")
    _assert_no_indirection_below(root, root / "skills", "canonical source")
    agents = sorted((root / "agents").glob("*.md"))
    if not agents:
        raise ValueError(f"{root / 'agents'}: no canonical agents found")
    for source in agents:
        if _is_link_or_reparse(source):
            raise ValueError(f"{source}: canonical source must not be a link/reparse point")
        outputs[COPILOT_AGENTS / f"{source.stem}.agent.md"] = render_copilot_agent(source).encode("utf-8")

    skill_files = _canonical_skill_files(root)
    if not any(path.name == "SKILL.md" for path in skill_files):
        raise ValueError(f"{root / 'skills'}: no canonical skills found")
    for source in skill_files:
        relative = source.relative_to(root / "skills")
        if source.name == "SKILL.md":
            copilot, _ = _portable_skill(source, "copilot")
            outputs[COPILOT_SKILLS / relative] = copilot
            continue
        suffix = source.suffix.lower()
        if suffix in ADAPT_TEXT_SUFFIXES:
            text = source.read_text(encoding="utf-8")
            outputs[COPILOT_SKILLS / relative] = adapt_text(text, "copilot").encode("utf-8")
        elif suffix in NORMALIZED_CODE_SUFFIXES:
            # Verbatim except line endings — read_text() normalizes CRLF/CR to LF via universal
            # newlines. No adapt_text: a script's tokens and shebang must survive unrewritten. A
            # non-UTF-8 asset (a UTF-16 .ps1, say) cannot be decoded to normalize, so it falls back
            # to a verbatim byte-copy — the pre-normalization behavior — rather than crashing.
            try:
                normalized = source.read_text(encoding="utf-8").encode("utf-8")
            except UnicodeDecodeError:
                # Preserve an undecodable asset without guessing its encoding.
                normalized = source.read_bytes()
            outputs[COPILOT_SKILLS / relative] = normalized
        else:
            content = source.read_bytes()
            outputs[COPILOT_SKILLS / relative] = content
    return outputs


def _actual_generated_files(root: Path) -> set[Path]:
    actual: set[Path] = set()
    for relative in GENERATED_ROOTS:
        base = root / relative
        _assert_no_indirection_below(root, base, "generated output")
        if not base.exists():
            continue
        if _is_link_or_reparse(base):
            raise ValueError(f"{base}: generated root must not be a link/reparse point")
        for current, directories, files in os.walk(base, followlinks=False):
            current_path = Path(current)
            for directory in list(directories):
                child = current_path / directory
                if _is_link_or_reparse(child):
                    raise ValueError(f"{child}: generated output must not be a link/reparse point")
            for filename in files:
                path = current_path / filename
                if _is_runtime_byproduct(path):
                    continue
                if _is_link_or_reparse(path):
                    raise ValueError(f"{path}: generated output must not be a link/reparse point")
                actual.add(path.relative_to(root))
    return actual


def validate_generated_outputs(root: Path) -> list[str]:
    try:
        expected = expected_outputs(root)
        actual = _actual_generated_files(root.resolve())
    except (OSError, UnicodeError, ValueError) as exc:
        return [str(exc)]
    failures: list[str] = []
    for path in sorted(set(expected) - actual):
        failures.append(f"{path.as_posix()}: generated output is missing; run adapter generator --write")
    for path in sorted(actual - set(expected)):
        failures.append(f"{path.as_posix()}: stale generated output")
    for relative in sorted(set(expected) & actual):
        if (root / relative).read_bytes() != expected[relative]:
            failures.append(f"{relative.as_posix()}: generated output drift")
    return failures


def _manifest(path: Path) -> dict:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"{path}: manifest must be a JSON object")
    return value


def validate_platform_contracts(root: Path) -> list[str]:
    failures: list[str] = []
    paths = [root / ".claude-plugin/plugin.json", root / "plugin.json"]
    manifests: list[dict] = []
    for path in paths:
        try:
            manifests.append(_manifest(path))
        except (OSError, json.JSONDecodeError, ValueError) as exc:
            failures.append(str(exc))
    if len(manifests) == len(paths):
        claude, copilot = manifests
        if claude.get("name") != PLUGIN_NAME:
            failures.append(f"{paths[0]}: name must match adapter PLUGIN_NAME {PLUGIN_NAME!r}")
        if "$schema" in copilot:
            failures.append(
                "plugin.json: selector-based Copilot format must not declare $schema without "
                "migrating skills to skills/ and Copilot-specific components to "
                "com.github.copilot/"
            )
        for field in IDENTITY_FIELDS:
            if copilot.get(field) != claude.get(field):
                failures.append(f"{paths[1]}: identity field {field!r} differs from Claude manifest")
        expected_components = {
            "agents": "./.github/agents/",
            "skills": "./.github/skills/",
            "hooks": "./hooks/copilot-hooks.json",
        }
        for field, expected in expected_components.items():
            if copilot.get(field) != expected:
                failures.append(f"plugin.json: {field} must be {expected!r}")
    try:
        hook = _manifest(root / "hooks/hooks.json")
        powershell = next((entry for entry in hook["hooks"]["PreToolUse"]
                           if entry.get("matcher") == "PowerShell"), None)
        if powershell is None or not any(
            item.get("shell") == "powershell" and "readonly-guard-hook.ps1" in item.get("command", "")
            for item in powershell.get("hooks", [])
        ):
            failures.append("hooks/hooks.json: PowerShell requires its native guard handler")
        command = hook["hooks"]["PreToolUse"][0]["hooks"][0]["command"]
        for token in ("${CLAUDE_PLUGIN_ROOT}", "readonly-guard.py", "python3 python py"):
            if token not in command:
                failures.append(f"hooks/hooks.json: command is missing {token!r}")
        if 'case "$IN"' in command:
            failures.append("hooks/hooks.json: raw-JSON prefilter bypasses the Python identity canary")
    except (OSError, json.JSONDecodeError, KeyError, IndexError, TypeError, ValueError) as exc:
        failures.append(f"hooks/hooks.json: invalid hook contract: {exc}")
    return failures


def _retired_generated_root_failures(root: Path) -> list[str]:
    failures: list[str] = []
    for retired in RETIRED_GENERATED_ROOTS:
        if (root / retired).exists():
            failures.append(
                f"{retired.as_posix()}: retired generated root is present on disk; a host can still "
                f"load it through an older configuration. Remove it."
            )
    return failures


def _gitattributes_failures(root: Path) -> list[str]:
    """The companion the byte gate needs: it cannot catch a .gitattributes regression itself.

    Removing an `eol=lf` rule passes on every machine whose files are already LF; only a fresh
    Windows clone then diverges. So assert the rules exist, and that nothing committed under a
    generated root already carries a CR byte (which a text=eol=lf rule is meant to prevent).
    """
    attributes = root / ".gitattributes"
    if not attributes.is_file():
        return [".gitattributes: missing; the cross-platform line-ending policy is unenforced"]
    text = attributes.read_text(encoding="utf-8")
    failures: list[str] = []
    for pattern in GITATTRIBUTES_REQUIRED_EOL:
        if not re.search(rf"(?m)^{re.escape(pattern)}\s+.*\beol=lf\b", text):
            failures.append(f".gitattributes: missing 'text eol=lf' rule for {pattern}")
    try:
        generated = _actual_generated_files(root)  # reuse the one walk + link/reparse guard
    except (OSError, ValueError):
        return failures  # a tree-integrity problem is validate_generated_outputs' to report
    for relative in sorted(generated):
        if relative.suffix.lower() not in LF_TEXT_SUFFIXES:
            continue  # only LF-governed text can carry a CR *regression*; binaries can't
        try:
            data = (root / relative).read_bytes()
        except OSError:
            continue
        if b"\r" not in data:
            continue
        try:
            data.decode("utf-8")
        except UnicodeDecodeError:
            continue  # a non-UTF-8 asset's 0x0D is encoding, not a line ending
        failures.append(f"{relative.as_posix()}: generated file carries a CR byte")
    return failures


def _generated_tree_failures(root: Path) -> list[str]:
    """Shared tree policy for fleet validation and the adapter CLI's post-write check."""
    # The CLI once omitted retired roots and printed PASS over stale host-loadable content.
    # Git ignores those roots, so neither caller may rely on Git to detect them.
    return (
        validate_generated_outputs(root)
        + _retired_generated_root_failures(root)
        + _gitattributes_failures(root)
    )


def validate_platform_support(root: Path) -> list[str]:
    return validate_platform_contracts(root) + _generated_tree_failures(root)


def write_generated_outputs(root: Path) -> int:
    root = root.resolve()
    outputs = expected_outputs(root)
    for relative in GENERATED_ROOTS:
        target = root / relative
        _assert_no_indirection_below(root, target, "generated root")
        if target.exists() and _is_link_or_reparse(target):
            raise ValueError(f"{target}: refusing to replace a link/reparse point")

    with tempfile.TemporaryDirectory(prefix=".adapter-stage-", dir=root) as temporary:
        stage = Path(temporary) / "new"
        backup = Path(temporary) / "old"
        for relative, content in outputs.items():
            destination = stage / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)

        moved: list[tuple[Path, Path | None]] = []
        try:
            for relative in GENERATED_ROOTS:
                destination = root / relative
                staged = stage / relative
                saved: Path | None = None
                if destination.exists():
                    saved = backup / relative
                    saved.parent.mkdir(parents=True, exist_ok=True)
                    os.replace(destination, saved)
                destination.parent.mkdir(parents=True, exist_ok=True)
                try:
                    os.replace(staged, destination)
                except OSError:
                    # The current root has already moved. Restore this iteration before the outer
                    # rollback handles roots that completed earlier; otherwise TemporaryDirectory
                    # cleanup would delete the only backup.
                    if saved is not None and saved.exists() and not destination.exists():
                        os.replace(saved, destination)
                    raise
                moved.append((destination, saved))
        except OSError:
            for destination, saved in reversed(moved):
                if destination.exists():
                    shutil.rmtree(destination)
                if saved is not None and saved.exists():
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    os.replace(saved, destination)
            raise
    return len(outputs)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="replace generated roots transactionally")
    parser.add_argument("--copilot-command-preview", type=Path,
                        help="export an SRE terminal/guard profile for an isolated VS Code canary; does not install it")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    try:
        contract_failures = validate_platform_contracts(root)
        if contract_failures:
            for failure in contract_failures:
                print(failure)
            return 1
        if args.copilot_command_preview is not None:
            if args.write:
                parser.error("export the command preview separately from --write")
            destination = args.copilot_command_preview
            destination.parent.mkdir(parents=True, exist_ok=True)
            with destination.open("x", encoding="utf-8", newline="\n") as stream:
                stream.write(render_copilot_agent(root / "agents/sre-assistant.md", command_preview=True))
            print(f"Exported unaccepted VS Code command preview: {destination}")
            return 0
        if args.write:
            count = write_generated_outputs(root)
            print(f"Generated {count} adapter file(s).")
        # Check the resulting tree; manifest validation must remain before any write.
        failures = _generated_tree_failures(root)
    except (OSError, UnicodeError, ValueError) as exc:
        print(exc)
        return 1
    if failures:
        for failure in failures:
            print(failure)
        return 1
    print("Platform adapters: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
